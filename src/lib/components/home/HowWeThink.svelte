<section class="ht hs" id="how-we-think" aria-labelledby="ht-h">
	<div class="in hs-head">
		<p class="mono label">How we think</p>
		<h2 id="ht-h">We start with the gap, not the brief.</h2>
		<p class="hs-p">
			Most projects begin with a list of features. Ours begin with a question: what are you trying
			to achieve, and what's standing in the way? The answer is usually a gap nobody has named yet.
		</p>
	</div>
	<div class="in">
		<ol class="hs-steps">
			<li class="hs-step" style="--s:0">
				<span class="mono hs-n">Step 01</span>
				<h3>Find the gap</h3>
				<p>
					Where are your customers being let down, by you or by everyone else in your market? That's
					where the opportunity sits.
				</p>
			</li>
			<li class="hs-step" style="--s:1">
				<span class="mono hs-n">Step 02</span>
				<h3>Name the outcome</h3>
				<p>
					More enquiries, fewer manual hours, a product people pay for. We agree on what success
					looks like before we agree on what to build.
				</p>
			</li>
			<li class="hs-step" style="--s:2">
				<span class="mono hs-n">Step 03</span>
				<h3>Build the shortest path</h3>
				<p>
					Software, brand, marketing, or all three. Only what closes the gap, and nothing that just
					looks busy.
				</p>
			</li>
		</ol>
		<p class="hs-close">
			The best opportunities aren't hidden. They're just sitting in the gaps everyone walks past.
		</p>
	</div>
</section>
